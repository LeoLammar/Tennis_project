package model;

/**
 * Énumération représentant les différents styles de jeu qu'un joueur peut adopter.
 */
public enum PlayStyle {
    AGGRESSIVE, // Style offensif, puissant, prenant des risques.
    DEFENSIVE,  // Style basé sur la régularité, le contre et l'endurance.
    ALL_AROUND  // Style équilibré, capable de s'adapter.
}